"""Publish the B4 review page next to the renders it is about.

The reviewed page lives in `reviews/b4-round/index.html` (that one is committed - it is the
source, and it carries its own copies of the images so the folder can be shared standalone).

This writes a second copy into the round directory itself, `v6/round-b4/review.html`, whose
images are RELATIVE PATHS to the real renders - `views/`, `poses/`, `../../reference/`. That
is the copy to open when you want to read the verdict and the picture it is about side by
side, since the renders are hundreds of megabytes of working material that git deliberately
does not carry (see .gitignore: assets/characters/**/v6/).

Re-run after every edit to index.html; the round copy is generated, never hand-edited.

  python reviews/b4-round/publish.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'reviews/b4-round/index.html'
BASE = ROOT / 'assets/characters/lingxi/v6'

# The page now shows every clip twice - `poses-b4/` is the round as reviewed, `poses-fix/` is
# the same clip after the action fixes. Each round directory holds one of the two, so each copy
# of the page points its own half at local files and the other half at the sibling round.
TARGETS = {
    # the fixed round: its own poses/ are the AFTER renders, the before ones were copied in
    'round-b4b': {'poses-fix/': 'poses/', 'poses-b4/': 'poses-before/'},
    # the reviewed round: its poses/ are the BEFORE renders; the after ones live next door
    'round-b4': {'poses-b4/': 'poses/', 'poses-fix/': '../round-b4b/poses/'},
}

# src="x" in the source page -> path relative to the round directory
MAP = {
    'front.png': 'views/front.png',
    'side.png': 'views/side.png',
    'face.png': 'views/face.png',
    'threequarter.png': 'views/threequarter.png',
    'turnaround-v1.png': '../../reference/turnaround-v1.png',
    'lingxi-ref-face-closeup.png': '../../reference/lingxi-ref-face-closeup.png',
}
CLIPS = ['Idle', 'Walk', 'Run', 'Jump', 'LieDown', 'SideLie', 'Sleep', 'Curious', 'Happy',
         'Yawn', 'Lick', 'Bite', 'Knead', 'Stretch', 'PawPlay']

html_src = SRC.read_text(encoding='utf-8')


for round_name, pose_map in TARGETS.items():
    ROUND = BASE / round_name
    OUT = ROUND / 'review.html'
    html = html_src

    def fix(m):
        src = m.group(1)
        if src in MAP:
            return f'src="{MAP[src]}"'
        for prefix, dest in pose_map.items():
            if src.startswith(prefix):
                return f'src="{dest}{src[len(prefix):]}"'
        return m.group(0)

    html, n = re.subn(r'src="([^"]+)"', fix, html)
    # The fifteen clip thumbnails come from the same rule: in the source they are written as a
    # JS template `src="poses-b4/${n}.png"` / `poses-fix/${n}.png`, so the src regex above
    # catches them too. 7 = the six stills plus the JS template that builds the thumbnails.
    assert n >= 7, f'only {n} image references seen - did index.html change shape?'

    # say where this copy came from, so nobody edits it by hand
    html = html.replace('<title>', '<!-- GENERATED by reviews/b4-round/publish.py from '
                        'reviews/b4-round/index.html - edit that one. -->\n<title>', 1)

    html = html.replace('</nav>',
                        '</nav>\n<div class="sub" style="margin:-8px 0 0">这一份的图片直接引用本目录的 '
                        '<code>views/</code>、<code>poses/</code> 和 <code>../../reference/</code>，'
                        '所以结论和它所讲的那张渲染图就在同一个文件夹里。'
                        '真源是 <code>reviews/b4-round/index.html</code>，本文件由 '
                        '<code>publish.py</code> 生成，不要手改。</div>', 1)

    OUT.write_text(html, encoding='utf-8')

    # the measurements travel with the page: they are the evidence, not the prose
    for name, dest in (('clips-before.json', 'review-clips-before.json'),
                       ('clips-fix.json', 'review-clips-fix.json'),
                       ('audit.json', 'review-parts.json')):
        data = json.loads((SRC.parent / name).read_text())
        (ROUND / dest).write_text(json.dumps(data, ensure_ascii=False, indent=1))

    # the JS templates are filled in at runtime, so they are not files to look for
    missing = [p for p in re.findall(r'src="([^"]+)"', html)
               if '${' not in p and not (ROUND / p).exists()]
    print('wrote', OUT)
    print('  images rewritten:', n, '| missing next to the page:', missing or 'none')
