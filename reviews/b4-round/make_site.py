#!/usr/bin/env python3
"""把 b4-round 的审阅页做成可发布的静态站点（手机友好 + 单文件离线版）。

- 把 index.html 引用的 PNG 全部压成 JPEG 落到 site/img/（不碰原图）
- 改写 src、加 loading=lazy、补手机端 CSS（.pair 竖排、表格不撑破）
- 额外产出一份 base64 内联的单文件 HTML，可用微信/AirDrop 直接打开

用法：
  python3 reviews/b4-round/make_site.py
"""
import base64
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = HERE                      # reviews/b4-round
SITE = os.path.join(HERE, 'site')
OUT = os.path.join(HERE, 'lingxi-review-offline.html')

# 只压 index.html 真正引用的图（face34 / contact-sheet 页面里没用到，不压）
VIEWS = ['turnaround-v1', 'front', 'side', 'face',
         'threequarter', 'lingxi-ref-face-closeup',
         'lid-before-blink', 'lid-after-blink', 'lid-before-happy',
         'lid-after-happy', 'lid-after-idle']
CLIPS = ['Bite', 'Curious', 'Happy', 'Idle', 'Jump', 'Knead', 'Lick', 'LieDown',
         'PawPlay', 'Run', 'SideLie', 'Sleep', 'Stretch', 'Walk', 'Yawn']

# (longest edge, jpeg quality)
VIEW_LIMIT = (900, 85)
POSE_LIMIT = (480, 84)

EXTRA_CSS = """
@media(max-width:700px){
  .wrap{padding:0 14px}
  body{padding-bottom:60px;font-size:14px}
  nav{flex-wrap:nowrap;overflow-x:auto;-webkit-overflow-scrolling:touch;padding:8px 0 4px}
  nav a{white-space:nowrap;font-size:13px;padding:3px 10px}
  h1{font-size:20px}h2{font-size:17px;margin:32px 0 6px}
  /* 手机上前后对照改竖排，否则每张只有 170px 太看不清 */
  .pair{grid-template-columns:1fr}
  .pair .ph b{font-size:12px;padding:2px 8px}
  .c .nm{font-size:12px}.c .st{font-size:10px}
  table{font-size:12px}th,td{padding:6px 5px}
  th,td{word-break:break-word}
  pre,code{font-size:11.5px}
}
img{height:auto}
"""

ROBOT = ('<!-- GENERATED by make_site.py: 压缩图 + 手机端排版，原图仍在 b4-round/ 根目录 -->')

# 缓存版本号：图换批次必须递增，否则手机浏览器拿旧图（文件名不变）
IMG_VER = 'round-i-1001'


def conv(src, dst, limit, quality):
    from PIL import Image
    im = Image.open(src).convert('RGB')
    w, h = im.size
    m = max(w, h)
    if m > limit:
        s = limit / m
        im = im.resize((round(w * s), round(h * s)), Image.LANCZOS)
    im.save(dst, 'JPEG', quality=quality, optimize=True, progressive=True)
    return im.size, os.path.getsize(dst)


def build_images():
    img_dir = os.path.join(SITE, 'img-' + IMG_VER)
    os.makedirs(img_dir, exist_ok=True)
    jobs = []
    for n in VIEWS:
        jobs.append((os.path.join(SRC, n + '.png'), os.path.join(img_dir, n + '.jpg'),
                     VIEW_LIMIT))
    for c in CLIPS:
        for k in ('b4', 'fix'):
            jobs.append((os.path.join(SRC, 'poses-%s' % k, c + '.png'),
                         os.path.join(img_dir, 'poses-%s-%s.jpg' % (k, c)), POSE_LIMIT))
    rows, miss = [], []
    for s, d, lim in jobs:
        if not os.path.exists(s):
            miss.append(os.path.relpath(s, SRC))
            continue
        size, n = conv(s, d, *lim)
        rows.append((os.path.relpath(d, SITE), size, n))  # rel 含版本目录
    tot = sum(r[2] for r in rows)
    print('images: %d, %.2f MB' % (len(rows), tot / 1048576))
    for m in miss:
        print('  MISSING', m)
    return miss


def rewrite_html():
    p = os.path.join(SRC, 'index.html')
    html = open(p, encoding='utf-8').read()
    o = 0
    # 卡片视图图
    for n in VIEWS:
        c = html.count('src="%s.png"' % n)
        assert c > 0, n
        o += c
        html = html.replace('src="%s.png"' % n, 'src="img-%s/%s.jpg"' % (IMG_VER, n))
    # 动作图（模板字符串，两处 grid 都命中）
    for tag in ('b4', 'fix'):
        old = 'src="poses-%s/${n}.png"' % tag
        new = 'src="img-%s/poses-%s-${n}.jpg"' % (IMG_VER, tag)
        c = html.count(old)
        assert c >= 1, (tag, c)
        o += c
        html = html.replace(old, new)
    # lazy / async（幂等：先清掉旧属性再加，目录名原样保留）
    html, _ = re.subn(r'<img (loading="lazy" )?decoding="async" (src="img-[^/]+/)',
                      r'<img \2', html)
    html, n2 = re.subn(r'<img src="(img-[^/]+/[^"]+")',
                       r'<img loading="lazy" decoding="async" src="\1', html)
    # 注入手机 CSS
    assert 'img{height:auto}' not in html
    html = html.replace('</style>', EXTRA_CSS + '</style>')
    # 版本角标：用户一眼能确认看到的是哪批图
    badge = ('<div style="position:fixed;right:10px;bottom:10px;z-index:9;'
             'background:rgba(16,16,20,.85);color:#9a97a0;font-size:11px;'
             'padding:2px 8px;border-radius:8px">img v=%s</div>' % IMG_VER)
    html, nb = re.subn(r'(<body[^>]*>)', lambda m: m.group(1) + badge, html, count=1)
    assert nb == 1
    html = html.replace('<title>', '<meta name="color-scheme" content="dark light">'
                                   '<title>', 1)
    html = ROBOT + '\n' + html
    os.makedirs(SITE, exist_ok=True)
    out = os.path.join(SITE, 'index.html')
    open(out, 'w', encoding='utf-8').write(html)
    print('html: %d src rewrites, %d lazy imgs, %.1f KB' % (o, n2, os.path.getsize(out) / 1024))
    return out


def build_offline(index_html_path):
    """把压缩后的图 base64 内联，产出一个能靠微信/AirDrop 直接打开的 HTML。

    30 张动作图走的是 JS 模板字符串（src="img/poses-b4/${n}.jpg"），
    没法逐个替换，所以内联成一张 JS 映射表 + 模板里改成 ${IMG['b4'][n]}。
    """
    html = open(index_html_path, encoding='utf-8').read()
    cache = {}

    def b64(path):
        if path not in cache:
            cache[path] = 'data:image/jpeg;base64,' + \
                base64.b64encode(open(path, 'rb').read()).decode()
        return cache[path]

    maps = {}
    for tag in ('b4', 'fix'):
        maps[tag] = {}
        for c in CLIPS:
            p = os.path.join(SITE, 'img-' + IMG_VER, 'poses-%s-%s.jpg' % (tag, c))
            if os.path.exists(p):
                maps[tag][c] = b64(p)
    # 1) 卡片图：直接内联
    def repl(m):
        rel = m.group(1)
        if '${' in rel:      # 模板串留给第 2 步
            return m.group(0)
        return 'src="%s"' % b64(os.path.join(SITE, 'img-' + IMG_VER, rel))

    html, n = re.subn(r'src="img-[^"]+?/([^"]+\.jpg)"', repl, html)
    n = len(cache)
    # 2) 动作图：模板改成查表
    for tag in ('b4', 'fix'):
        tpl = 'src="img-%s/poses-%s-${n}.jpg"' % (IMG_VER, tag)
        assert tpl in html, tpl
        html = html.replace(tpl, "src=\"${IMG['%s'][n]}\"" % tag)
    if maps['b4'] or maps['fix']:
        html = html.replace('<script>\nconst CLIPS',
                            '<script>const IMG=%s;</script>\n<script>\nconst CLIPS'
                            % json.dumps(maps, ensure_ascii=False), 1)
    open(OUT, 'w', encoding='utf-8').write(html)
    print('offline: %d inlined, %.2f MB' % (n, os.path.getsize(OUT) / 1048576))


if __name__ == '__main__':
    if os.path.isdir(SITE):
        shutil.rmtree(SITE)
    miss = build_images()
    out = rewrite_html()
    build_offline(out)
    print('site ->', SITE)
    sys.exit(1 if miss else 0)
